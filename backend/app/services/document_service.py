"""Strategy documents and their exports (stage 8)."""

from __future__ import annotations

import io
import logging
from typing import Any

from app.core.errors import NotFoundError

logger = logging.getLogger("optistratix.documents")


def get_document(repo: Any, project_id: str) -> dict[str, Any] | None:
    repo.get_project(project_id)
    return repo.get_document(project_id)


def require_document(repo: Any, project_id: str) -> dict[str, Any]:
    document = get_document(repo, project_id)
    if document is None:
        raise NotFoundError(
            "No document has been generated for this project yet. Approve a strategy first."
        )
    return document


def render_markdown(document: dict[str, Any]) -> bytes:
    body = f"# {document['title']}\n\n{document['content']}\n"
    return body.encode("utf-8")


def render_pdf(document: dict[str, Any]) -> bytes:
    """Renders the document to PDF with reportlab.

    Raises ImportError if reportlab is absent; the route turns that into a 503
    rather than a 500, because it is a deployment gap and not a bug.
    """
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=22 * mm,
        rightMargin=22 * mm,
        topMargin=22 * mm,
        bottomMargin=20 * mm,
        title=document["title"],
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle", parent=styles["Title"], alignment=TA_LEFT, spaceAfter=6
    )
    heading_style = ParagraphStyle(
        "DocHeading", parent=styles["Heading2"], spaceBefore=14, spaceAfter=6
    )
    body_style = ParagraphStyle(
        "DocBody", parent=styles["BodyText"], leading=15, spaceAfter=8
    )

    flow: list[Any] = [
        Paragraph(_escape(document["title"]), title_style),
        Paragraph("Generated by OptiStratixAI", styles["Italic"]),
        Spacer(1, 10),
    ]

    for section in sorted(document.get("sections", []), key=lambda s: s.get("order", 0)):
        flow.append(Paragraph(_escape(section["heading"]), heading_style))
        flow.append(Paragraph(_escape(section["body"]), body_style))

    doc.build(flow)
    return buffer.getvalue()


def render_docx(document: dict[str, Any]) -> bytes:
    """Renders the document to DOCX with python-docx."""
    from docx import Document as DocxDocument

    docx = DocxDocument()
    docx.add_heading(document["title"], level=0)
    docx.add_paragraph("Generated by OptiStratixAI").italic = True

    for section in sorted(document.get("sections", []), key=lambda s: s.get("order", 0)):
        docx.add_heading(section["heading"], level=1)
        docx.add_paragraph(section["body"])

    buffer = io.BytesIO()
    docx.save(buffer)
    return buffer.getvalue()


def _escape(text: str) -> str:
    """reportlab's Paragraph parses a mini-HTML dialect, so raw angle brackets
    and ampersands have to be escaped or the build fails."""
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )
